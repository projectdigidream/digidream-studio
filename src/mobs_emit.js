//
// The module's monsters, as the mobs.load{} file every map of the module
// declares. One file per module, because mobs.load runs once per level and
// refuses a second call (maps/scripts/mobs.lua).
//
// The table is written exactly as the module document keeps it -- the studio's
// brain editor edits the same JSON the vocabulary describes -- so there is no
// translation to get wrong, only the number rule lua.js enforces.
//
import { toLua, block } from './lua.js'

/**
 * @param module  the module document: { id, mobs: { missiles: {}, mobs: {} } }
 * @returns the file's text, or null when the module defines nothing
 */
export function emitMobsLua (module) {
  const table = { missiles: module.mobs?.missiles ?? {}, mobs: module.mobs?.mobs ?? {} }
  if (Object.keys(table.missiles).length === 0 && Object.keys(table.mobs).length === 0) return null
  const body = [
    '--',
    `-- GENERATED by the studio from module.studio.json (module: ${module.id}).`,
    '-- Every edit here is overwritten on the next bake; edit the mobs in the studio.',
    '--',
    `mobs.load${toLua(table)}`
  ].join('\n')
  return block('mobs', body) + '\n'
}

/**
 * How long a flinch lasts (docs/MOBS.md `pain_time`): the pain state's own
 * ticks, and -- switched on -- a share of each hit on top, capped. Said with
 * what a few hits come to, by the runtime's own sum (mobs.lua pain_ticks_for).
 */
export function painLength (m, damage, base = m.states?.pain?.ticks) {
  if (base === undefined || base === null) return null
  let t = Number(base)
  const pt = m.pain_time
  if (pt?.per_damage !== undefined && damage > 0) t += Math.max(0, Math.floor(Math.floor(damage) * Number(pt.per_damage)))
  if (pt?.max !== undefined && t > pt.max) t = pt.max
  return Math.max(1, t)
}
