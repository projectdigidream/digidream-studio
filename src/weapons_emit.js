//
// The module's arsenal, as the weapons.load{} file every map of the module
// declares: its ammunition pools, the player's health ceilings, the weapons
// themselves and what a pickup grants.
//
// A weapon is a PHASE MACHINE (maps/scripts/weapon_vocab.lua) and has the same
// shape a monster's brain does -- named nodes with `ticks`, `next`, a
// `sequence` of actions and `transitions` that are checked in order. That is
// why the studio edits both with one graph: automatic fire, a charge, a combo
// and an alt-fire are arrangements of that graph rather than flags.
//
// The table is written exactly as the module document keeps it, so there is no
// translation to get wrong -- only the number rule lua.js enforces.
//
import { tidySwings } from './swings_emit.js'
import { toLua, block } from './lua.js'

/**
 * Whether the module arms anybody.
 *
 * A WEAPON OR A PICKUP, not a pool or a health ceiling. Opening the arsenal
 * window creates the container it edits, and a module that merely has an empty
 * container must not start emitting a file and spending three of a map's eight
 * script slots on a runtime it never uses.
 */
export function hasWeapons (module) {
  const w = module.weapons
  if (!w) return false
  return Object.keys(w.weapons ?? {}).length > 0 || Object.keys(w.pickups ?? {}).length > 0
}

/**
 * @param module  the module document: { id, weapons: { ammo, health, weapons, pickups } }
 * @returns the file's text, or null when the module arms nobody
 */
export function emitWeaponsLua (module) {
  if (!hasWeapons(module)) return null
  const w = module.weapons
  const table = {}
  if (Object.keys(w.ammo ?? {}).length) table.ammo = w.ammo
  if (w.health) table.health = w.health
  if (Object.keys(w.weapons ?? {}).length) table.weapons = w.weapons
  if (Object.keys(w.pickups ?? {}).length) table.pickups = w.pickups
  const body = [
    '--',
    `-- GENERATED by the studio from module.studio.json (module: ${module.id}).`,
    '-- Every edit here is overwritten on the next bake; edit the weapons in the studio.',
    '--',
    `weapons.load${toLua(table)}`
  ].join('\n')
  return block('weapons', body) + '\n'
}

/** A fresh arsenal: one pool, the usual ceilings, no weapons yet. */
export function newArsenal () {
  return {
    ammo: { bullets: { label: 'Bullets', max: 200, initial: 50, order: 1 } },
    health: { max: 100, bonus_max: 200 },
    weapons: {},
    pickups: {}
  }
}

/**
 * A weapon that works the moment it is made: it rests, it fires when the
 * button goes down, and it comes back. Anything more -- automatic fire, a
 * charge, a combo -- is an edge added to that graph.
 */
export function newWeapon (module, raw) {
  module.weapons ??= newArsenal()
  const name = String(raw ?? '').toLowerCase().replace(/[^a-z0-9_]/g, '')
  if (!name || module.weapons.weapons[name]) return null
  const orders = Object.values(module.weapons.weapons).map((x) => x.order ?? 0)
  module.weapons.weapons[name] = {
    label: name.charAt(0).toUpperCase() + name.slice(1),
    order: orders.length ? Math.max(...orders) + 1 : 1,
    initial: 'ready',
    phases: {
      ready: { anim: 0, transitions: [{ when: [{ cond: 'button_pressed' }], to: 'fire' }] },
      fire: { anim: 2, ticks: 12, next: 'ready', sequence: [{ at: 0, action: 'hitscan', damage: 10, range: '32' }] }
    }
  }
  return name
}

export function deleteWeapon (module, name) {
  delete module.weapons?.weapons?.[name]
  for (const [pname, p] of Object.entries(module.weapons?.pickups ?? {})) {
    if (p.weapon === name) delete module.weapons.pickups[pname]
  }
  if (module.layouts) delete module.layouts[`weapon:${name}`]
  // Its look in the game goes with it (swings_emit.js).
  if (module.swings?.weapons) { delete module.swings.weapons[name]; tidySwings(module) }
}
